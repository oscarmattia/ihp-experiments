#!/usr/bin/env bash
# Install IHP SG13G2 EM tooling (openEMS primary; Palace optional) — idempotent.
#
# Usage:
#   ./scripts/install-ihp-em.sh
#   IHP_EDA_ROOT=/custom/path ./scripts/install-ihp-em.sh --skip-palace
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

IHP_EDA_ROOT="${IHP_EDA_ROOT:-$HOME/.local/share/ihp-eda}"
IHP_TOOLS_PREFIX="${IHP_TOOLS_PREFIX:-$IHP_EDA_ROOT/tools}"
IHP_SRC_DIR="${IHP_SRC_DIR:-$IHP_EDA_ROOT/src}"
PDK_ROOT="${PDK_ROOT:-$IHP_EDA_ROOT/IHP-Open-PDK}"
PDK="${PDK:-ihp-sg13g2}"

OPENEMS_PROJECT_REPO="${OPENEMS_PROJECT_REPO:-https://github.com/thliebig/openEMS-Project.git}"
OPENEMS_REPO="${OPENEMS_REPO:-https://github.com/thliebig/openEMS.git}"
PALACE_IMAGE="${PALACE_IMAGE:-oras://ghcr.io/volkermuehlhaus/palace_016:latest}"
PALACE_SIF="${PALACE_SIF:-$IHP_EDA_ROOT/palace.sif}"
EM_STATUS_FILE="${EM_STATUS_FILE:-$IHP_EDA_ROOT/em.status}"

SKIP_OPENEMS_BUILD=0
SKIP_PALACE=0
FORCE=0

log()  { printf '\n==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

have_cmd() { command -v "$1" >/dev/null 2>&1; }

usage() {
  cat <<EOF
Install IHP SG13G2 EM tooling (openEMS primary; Palace optional).

Options:
  --skip-openems-build   Install Python deps only; do not build openEMS binaries
  --skip-palace          Skip Palace / Apptainer image setup
  --force                Reinstall Python packages and rebuild openEMS when possible
  -h, --help             Show this help

Environment:
  IHP_EDA_ROOT           Install root (default: ~/.local/share/ihp-eda)
  PDK_ROOT               PDK checkout (default: \$IHP_EDA_ROOT/IHP-Open-PDK)
  PALACE_SIF             Palace Apptainer image path (default: \$IHP_EDA_ROOT/palace.sif)
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --skip-openems-build) SKIP_OPENEMS_BUILD=1 ;;
    --skip-palace) SKIP_PALACE=1 ;;
    --force) FORCE=1 ;;
    -h|--help) usage; exit 0 ;;
    *) die "Unknown option: $1" ;;
  esac
  shift
done

mem_total_gb() {
  local kb
  kb="$(awk '/^MemTotal:/ {print $2}' /proc/meminfo 2>/dev/null || echo 0)"
  echo $(( (kb + 1023 * 1024) / 1024 / 1024 ))
}

write_status() {
  local python_deps="$1"
  local openems_binary="$2"
  local palace="$3"
  mkdir -p "$IHP_EDA_ROOT"
  cat > "$EM_STATUS_FILE" <<EOF
# Auto-generated by install-ihp-em.sh — do not edit by hand.
python_deps=$python_deps
openems_binary=$openems_binary
palace=$palace
updated_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
}

ensure_venv() {
  if [[ -x "$IHP_EDA_ROOT/venv/bin/python" && "$FORCE" -eq 0 ]]; then
    log "Python venv already present at $IHP_EDA_ROOT/venv"
    return
  fi

  log "Creating Python venv at $IHP_EDA_ROOT/venv"
  if have_cmd uv; then
    if [[ "$FORCE" -eq 1 ]]; then
      uv venv "$IHP_EDA_ROOT/venv" --python python3 --clear
    else
      uv venv "$IHP_EDA_ROOT/venv" --python python3
    fi
  else
    python3 -m venv "$IHP_EDA_ROOT/venv"
  fi
}

venv_install() {
  if have_cmd uv; then
    uv pip install --python "$IHP_EDA_ROOT/venv/bin/python" "$@"
  else
    "$IHP_EDA_ROOT/venv/bin/pip" install "$@"
  fi
}

install_python_deps() {
  log "Installing EM Python dependencies into $IHP_EDA_ROOT/venv"
  ensure_venv

  local pkgs=(gdspy scikit-rf matplotlib numpy h5py)
  if [[ "$FORCE" -eq 1 ]]; then
    venv_install --upgrade "${pkgs[@]}"
  else
    venv_install "${pkgs[@]}"
  fi

  # Optional PyPI package — not fatal if absent.
  if venv_install gds2openEMS 2>/dev/null; then
    log "Installed gds2openEMS from PyPI"
  else
    warn "gds2openEMS not available on PyPI (or install failed); continuing without it"
  fi

  "$IHP_EDA_ROOT/venv/bin/python" - <<'PY'
import gdspy, skrf, numpy, h5py
print("EM Python imports OK:", gdspy.__name__, skrf.__name__, numpy.__name__, h5py.__name__)
PY
}

install_openems_build_deps() {
  if ! have_cmd sudo; then
    warn "sudo not available; openEMS build may fail without OS libraries"
    return 0
  fi
  log "Installing openEMS build dependencies (apt)"
  sudo apt-get update -qq
  # openEMS-Project typical deps on Ubuntu 24.04.
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \
    build-essential g++ gcc cmake git pkg-config \
    libstdc++-13-dev \
    libhdf5-dev libfftw3-dev libboost-all-dev \
    libvtk9-dev python3-dev \
    libtinyxml-dev libtinyxml2-dev \
    libcgal-dev libgmp-dev libmpfr-dev \
    || warn "Some openEMS build packages could not be installed"
}

find_openems_binary() {
  local candidate
  for candidate in \
    "$IHP_TOOLS_PREFIX/bin/openEMS" \
    "$IHP_TOOLS_PREFIX/bin/OpenEMS" \
    "$IHP_TOOLS_PREFIX/openEMS/bin/openEMS" \
    "$IHP_TOOLS_PREFIX/openEMS/bin/OpenEMS"; do
    if [[ -x "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  if have_cmd openEMS; then
    command -v openEMS
    return 0
  fi
  return 1
}

build_openems() {
  [[ "$SKIP_OPENEMS_BUILD" -eq 1 ]] && {
    log "Skipping openEMS build (--skip-openems-build)"
    return 0
  }

  if [[ "$FORCE" -eq 0 ]] && find_openems_binary >/dev/null; then
    log "openEMS binary already present: $(find_openems_binary)"
    return 0
  fi

  install_openems_build_deps || true

  local src="$IHP_SRC_DIR/openEMS-Project"
  log "Cloning/updating openEMS-Project from $OPENEMS_PROJECT_REPO"
  if [[ -d "$src/.git" ]]; then
    git -C "$src" fetch --depth 1 origin || true
    git -C "$src" pull --ff-only || true
    git -C "$src" submodule update --init --recursive || true
  else
    rm -rf "$src"
  fi

  if [[ ! -d "$src/.git" ]]; then
    if ! git clone --depth 1 --recurse-submodules "$OPENEMS_PROJECT_REPO" "$src"; then
      warn "Could not clone openEMS-Project (egress/network?). Trying standalone openEMS repo."
      src="$IHP_SRC_DIR/openEMS"
      rm -rf "$src"
      if ! git clone --depth 1 "$OPENEMS_REPO" "$src"; then
        warn "openEMS source clone failed; Python-only EM workflow remains available"
        return 1
      fi
    fi
  fi

  local build="$src/build"
  rm -rf "$build"
  mkdir -p "$build"

  log "Building openEMS under $IHP_TOOLS_PREFIX (this may take several minutes)"
  # Force GCC: some images default c++ to clang without a matching libstdc++.
  # ExternalProject sub-builds inherit CC/CXX from the environment.
  export CC="$(command -v gcc || echo gcc)"
  export CXX="$(command -v g++ || echo g++)"
  # Top-level ExternalProject makefile may lack an "install" target; subprojects
  # already install into CMAKE_INSTALL_PREFIX during "make". Treat binary presence
  # as success even if "make install" fails.
  if ! (
    cd "$build"
    cmake .. \
      -DCMAKE_INSTALL_PREFIX="$IHP_TOOLS_PREFIX/openEMS" \
      -DCMAKE_BUILD_TYPE=Release \
      -DCMAKE_CXX_COMPILER="$CXX" \
      -DCMAKE_C_COMPILER="$CC" \
      -DBUILD_APPCSXCAD=NO
    make -j"$(nproc)"
    make install || true
  ); then
    warn "openEMS build failed (missing deps, egress, or host limits). Python EM deps are still usable."
    return 1
  fi

  mkdir -p "$IHP_TOOLS_PREFIX/bin"
  local installed
  installed="$(find "$IHP_TOOLS_PREFIX/openEMS" -type f -name 'openEMS' 2>/dev/null | head -n1 || true)"
  if [[ -n "$installed" ]]; then
    ln -sfn "$installed" "$IHP_TOOLS_PREFIX/bin/openEMS"
    ln -sfn "$installed" "$HOME/.local/bin/openEMS" 2>/dev/null || true
    log "Installed openEMS: $installed"
  else
    warn "openEMS build finished but binary not found under $IHP_TOOLS_PREFIX/openEMS"
    return 1
  fi

  # Install Python bindings (CSXCAD + openEMS) into the EDA venv when present.
  local py="${IHP_EDA_ROOT}/venv/bin/python"
  if [[ -x "$py" ]]; then
    log "Installing openEMS Python bindings into venv"
    (
      export CSXCAD_ROOT_DIR="$IHP_TOOLS_PREFIX/openEMS"
      export OPENEMS_ROOT_DIR="$IHP_TOOLS_PREFIX/openEMS"
      export CPLUS_INCLUDE_PATH="$IHP_TOOLS_PREFIX/openEMS/include${CPLUS_INCLUDE_PATH:+:$CPLUS_INCLUDE_PATH}"
      export LIBRARY_PATH="$IHP_TOOLS_PREFIX/openEMS/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
      export LD_LIBRARY_PATH="$IHP_TOOLS_PREFIX/openEMS/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
      export CFLAGS="-I$IHP_TOOLS_PREFIX/openEMS/include"
      export CXXFLAGS="-I$IHP_TOOLS_PREFIX/openEMS/include"
      export LDFLAGS="-L$IHP_TOOLS_PREFIX/openEMS/lib"
      # Ensure pip exists (uv-managed venvs may omit it).
      if ! "$py" -m pip --version >/dev/null 2>&1; then
        if have_cmd uv; then
          uv pip install --python "$py" pip setuptools wheel cython
        else
          "$py" -m ensurepip --upgrade || true
        fi
      fi
      cd "$src/CSXCAD/python"
      "$py" setup.py build_ext --inplace \
        -I"$IHP_TOOLS_PREFIX/openEMS/include" \
        -L"$IHP_TOOLS_PREFIX/openEMS/lib" || true
      "$py" -m pip install --no-build-isolation --no-deps . || true
      cd "$src/openEMS/python"
      "$py" setup.py build_ext --inplace \
        -I"$IHP_TOOLS_PREFIX/openEMS/include" \
        -L"$IHP_TOOLS_PREFIX/openEMS/lib" || true
      "$py" -m pip install --no-build-isolation --no-deps . || true
      "$py" -c "from openEMS import openEMS; from CSXCAD import ContinuousStructure"
    ) || warn "openEMS Python bindings install failed; binary may still work"
  fi
}

install_appcsxcad_stub() {
  # PDK openEMS scripts launch AppCSXCAD for mesh preview; headless hosts need a stub.
  mkdir -p "$IHP_TOOLS_PREFIX/bin"
  local stub="$IHP_TOOLS_PREFIX/bin/AppCSXCAD"
  if [[ ! -x "$stub" ]]; then
    cat > "$stub" <<'STUB'
#!/bin/sh
# Headless stub — see docs/APPCSXCAD-STUB.md
echo "AppCSXCAD stub (headless); exiting 0"
exit 0
STUB
    chmod +x "$stub"
    log "Installed headless AppCSXCAD stub at $stub"
  fi
}

write_em_env() {
  log "Writing $IHP_EDA_ROOT/em.env.sh"
  local openems_root="$IHP_TOOLS_PREFIX/openEMS"
  local workflow="$PDK_ROOT/$PDK/libs.tech/openems/openems_ihp_sg13g2/workflow"
  mkdir -p "$IHP_EDA_ROOT"

  cat > "$IHP_EDA_ROOT/em.env.sh" <<EOF
# Auto-generated by install-ihp-em.sh — do not edit by hand.
export OPENEMS_ROOT="$openems_root"
export OPENEMS_WORKFLOW="$workflow"
export PATH="\$OPENEMS_ROOT/bin:\$IHP_TOOLS_PREFIX/bin:\$HOME/.local/bin:\$PATH"
export LD_LIBRARY_PATH="\$OPENEMS_ROOT/lib:\${LD_LIBRARY_PATH:-}"
export CPLUS_INCLUDE_PATH="\$OPENEMS_ROOT/include:\${CPLUS_INCLUDE_PATH:-}"
export LIBRARY_PATH="\$OPENEMS_ROOT/lib:\${LIBRARY_PATH:-}"
export PYTHONPATH="\$OPENEMS_WORKFLOW:\${PYTHONPATH:-}"
if [[ -f "$PALACE_SIF" ]]; then
  export PALACE_SIF="$PALACE_SIF"
fi
EOF

  if [[ -f "$IHP_EDA_ROOT/env.sh" ]]; then
    local marker="# >>> ihp-em >>>"
    local em_line='[ -f "$IHP_EDA_ROOT/em.env.sh" ] && . "$IHP_EDA_ROOT/em.env.sh"'
    if ! grep -qF "$marker" "$IHP_EDA_ROOT/env.sh"; then
      cat >> "$IHP_EDA_ROOT/env.sh" <<EOF

$marker
$em_line
# <<< ihp-em <<<
EOF
      log "Appended EM source hook to $IHP_EDA_ROOT/env.sh"
    fi
  else
    warn "Main env.sh not found at $IHP_EDA_ROOT/env.sh — source em.env.sh manually"
  fi
}

apptainer_cmd() {
  if have_cmd apptainer; then
    printf '%s\n' apptainer
    return 0
  fi
  if have_cmd singularity; then
    printf '%s\n' singularity
    return 0
  fi
  return 1
}

install_palace() {
  [[ "$SKIP_PALACE" -eq 1 ]] && {
    log "Skipping Palace (--skip-palace)"
    return 0
  }

  local mem_gb
  mem_gb="$(mem_total_gb)"
  if [[ "$mem_gb" -lt 28 ]]; then
    warn "Host RAM is ~${mem_gb}GB (< 28GB MemTotal); skipping Palace solver image pull"
    warn "Palace FEM is recommended on hosts with >= 32GB RAM and Apptainer"
    return 0
  fi

  log "Installing Palace Python helpers (gds2palace, gmsh)"
  ensure_venv
  venv_install gds2palace gmsh || warn "gds2palace/gmsh pip install failed"

  local runner
  if ! runner="$(apptainer_cmd)"; then
    log "Apptainer/Singularity not found; attempting apt install apptainer"
    if have_cmd sudo; then
      sudo apt-get update -qq
      sudo DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends apptainer \
        || warn "Could not install apptainer via apt; skipping Palace image"
    else
      warn "Apptainer/Singularity missing and sudo unavailable; skipping Palace image"
    fi
    runner="$(apptainer_cmd || true)"
  fi

  if [[ -z "${runner:-}" ]]; then
    warn "Palace container runtime unavailable; gds2palace/gmsh may still be useful for mesh prep"
    return 0
  fi

  if [[ -f "$PALACE_SIF" && "$FORCE" -eq 0 ]]; then
    log "Palace image already present: $PALACE_SIF"
    return 0
  fi

  log "Pulling Palace image to $PALACE_SIF"
  mkdir -p "$(dirname "$PALACE_SIF")"
  if ! "$runner" pull "$PALACE_SIF" "$PALACE_IMAGE"; then
    warn "Palace image pull failed (egress/registry?). Python Palace helpers may still work for mesh export."
    return 0
  fi
  log "Palace image ready: $PALACE_SIF"
}

print_summary() {
  local python_deps=ok
  local openems_status=missing
  local palace_status=skipped

  if find_openems_binary >/dev/null 2>&1; then
    openems_status=ok
  fi

  if [[ "$SKIP_PALACE" -eq 0 ]]; then
    if [[ -f "$PALACE_SIF" ]]; then
      palace_status=ok
    elif [[ "$(mem_total_gb)" -lt 28 ]]; then
      palace_status=skipped_low_ram
    else
      palace_status=missing
    fi
  fi

  write_status "$python_deps" "$openems_status" "$palace_status"

  cat <<EOF

============================================================
IHP EM environment
============================================================
IHP_EDA_ROOT       = $IHP_EDA_ROOT
OPENEMS_WORKFLOW   = $PDK_ROOT/$PDK/libs.tech/openems/openems_ihp_sg13g2/workflow
openEMS binary     = $(find_openems_binary 2>/dev/null || echo MISSING)
Palace image       = $([ -f "$PALACE_SIF" ] && echo "$PALACE_SIF" || echo MISSING/SKIPPED)
Status file        = $EM_STATUS_FILE

Activate:
  source $IHP_EDA_ROOT/env.sh
  # or: source $IHP_EDA_ROOT/em.env.sh

Verify:
  $REPO_ROOT/scripts/verify-ihp-em.sh
============================================================
EOF
}

main() {
  log "IHP EM install starting (root=$IHP_EDA_ROOT)"
  mkdir -p "$IHP_EDA_ROOT" "$IHP_TOOLS_PREFIX/bin" "$IHP_SRC_DIR" "$HOME/.local/bin"
  export PATH="$IHP_TOOLS_PREFIX/bin:$HOME/.local/bin:$PATH"

  local python_ok=0
  local openems_ok=0

  if install_python_deps; then
    python_ok=1
  else
    warn "EM Python dependency install failed"
  fi

  if build_openems; then
    openems_ok=1
  fi

  install_appcsxcad_stub
  write_em_env
  install_palace || warn "Palace setup encountered errors (non-fatal)"

  print_summary

  if [[ "$python_ok" -eq 1 ]]; then
    exit 0
  fi
  die "EM Python dependencies are required but failed to install"
}

main "$@"
